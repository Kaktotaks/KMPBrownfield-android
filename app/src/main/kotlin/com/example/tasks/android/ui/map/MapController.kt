/** Space the map must keep free when it frames something, in px (the selector on top, the sheet at the bottom). */
internal data class ViewportInsets(val top: Int, val bottom: Int, val side: Int = 0)

/**
 * Everything that talks to MapLibre: the style (generated by shared `MapStyle`), the GeoJSON route layers (§3.2),
 * camera moves and the projection used by the Compose pin overlay. No routing or style logic lives here: colours,
 * widths and dashes come from `MapStyle.routePalette`, the geometry from the shared `Route`.
 *
 * [tick] changes on every camera frame and style load; the overlay reads it inside layout / draw lambdas, so pins follow
 * the map without recomposing.
 */
internal class MapController {
    var map: MapLibreMap? = null
        private set
    var tick by mutableIntStateOf(0)
        private set
    var styleReady by mutableStateOf(false)
        private set

    /** Set by the host: called with `true` when tiles failed / the network is gone, `false` once the map rendered again. */
    var onStyleLoaded: (() -> Unit)? = null

    /** `true` once the camera has been framed once (later frames animate). */
    var hasFitted = false

    /** Retry: loads the style again so tiles are requested again. */
    fun reload(dark: Boolean, reduceMotion: Boolean) = loadStyle(dark, reduceMotion)

    private var palette: RoutePalette = MapStyle.routePalette(false)
    private var dark = false
    private var lines: RouteLines = RouteLines.None
    private var dim = false
    private var drawProgress = 1f
    private var animator: ValueAnimator? = null
    private var reduceMotion = false

    // region lifecycle

    fun attach(map: MapLibreMap) {
        this.map = map
        map.uiSettings.isCompassEnabled = false
        map.uiSettings.isLogoEnabled = false
        map.uiSettings.isRotateGesturesEnabled = false
        map.uiSettings.isTiltGesturesEnabled = false
        map.setMinZoomPreference(10.0)
        map.setMaxZoomPreference(19.0)
        map.addOnCameraMoveListener { tick++ }
        map.addOnCameraIdleListener { tick++ }
    }

    fun detach() {
        animator?.cancel()
        animator = null
        map = null
        styleReady = false
    }

    /** Loads the shared style for the appearance and (re)installs the route layers. */
    fun loadStyle(dark: Boolean, reduceMotion: Boolean) {
        val m = map ?: return
        this.dark = dark
        this.reduceMotion = reduceMotion
        palette = MapStyle.routePalette(dark)
        styleReady = false
        m.setStyle(Style.Builder().fromJson(MapStyle.json(dark))) { style ->
            installRouteLayers(style)
            styleReady = true
            applyLines(animate = false)
            tick++
            onStyleLoaded?.invoke()
        }
    }

    fun setAttributionMargins(leftPx: Int, bottomPx: Int) {
        val ui = map?.uiSettings ?: return
        ui.isAttributionEnabled = true
        ui.attributionGravity = android.view.Gravity.BOTTOM or android.view.Gravity.START
        ui.setAttributionMargins(leftPx, 0, 0, bottomPx)
    }

    // endregion

    // region projection

    fun project(point: GeoPoint): Offset? {
        @Suppress("UNUSED_EXPRESSION") tick // subscribe the caller (layout / draw lambda) to camera changes
        val p: PointF = map?.projection?.toScreenLocation(LatLng(point.lat, point.lng)) ?: return null
        return Offset(p.x, p.y)
    }

    fun target(): GeoPoint? = map?.cameraPosition?.target?.let { GeoPoint(it.latitude, it.longitude) }

    /** The place under a screen point (px, relative to the map view). */
    fun fromScreen(x: Float, y: Float): GeoPoint? =
        map?.projection?.fromScreenLocation(PointF(x, y))?.let { GeoPoint(it.latitude, it.longitude) }

    // endregion

    // region camera

    /** Frames [points] inside the free area (§6: top = selector bottom + 24, bottom = sheet + 24, sides 48). */
    fun fit(points: List<GeoPoint>, padding: CameraPaddingPx, animate: Boolean) {
        val m = map ?: return
        val latLngs = points.map { LatLng(it.lat, it.lng) }.distinct()
        if (latLngs.isEmpty()) return
        if (latLngs.size == 1) {
            focus(points.first(), ViewportInsets(padding.top, padding.bottom), animate, zoom = 14.0)
            return
        }
        val bounds = LatLngBounds.Builder().includes(latLngs).build()
        val position = m.getCameraForLatLngBounds(bounds, intArrayOf(padding.left, padding.top, padding.right, padding.bottom)) ?: return
        val clamped = CameraPosition.Builder(position).zoom(position.zoom.coerceAtMost(17.0)).build()
        move(CameraUpdateFactory.newCameraPosition(clamped), animate, MapMotion.CAMERA_FIT_MS)
    }

    /**
     * Puts [point] in the middle of the free area between the insets (e.g. "centres the pin above the task sheet").
     * [zoom] also sets a zoom level (used when there is only one point to frame). Works in Web-Mercator metres so
     * no padding state is left on the camera (the projection used for the pins stays the plain view projection).
     */
    fun focus(point: GeoPoint, insets: ViewportInsets, animate: Boolean, zoom: Double? = null) {
        val m = map ?: return
        val view = mapView ?: return
        val h = view.height
        if (view.width == 0 || h == 0) return
        val z = zoom ?: m.cameraPosition.zoom
        // The pin must appear dy px below the view's centre (negative = above it); the camera centre moves the other way.
        val dy = insets.top + (h - insets.top - insets.bottom) / 2f - h / 2f
        val density = view.resources.displayMetrics.density
        val metersPerPx = 40_075_016.686 * Math.cos(Math.toRadians(point.lat)) / (512.0 * Math.pow(2.0, z) * density)
        val dLat = dy * metersPerPx / 111_320.0
        val target = LatLng(point.lat + dLat, point.lng)
        move(CameraUpdateFactory.newCameraPosition(CameraPosition.Builder().target(target).zoom(z).build()), animate, MapMotion.CAMERA_FIT_MS)
    }

    fun centerOn(point: GeoPoint, animate: Boolean) {
        move(CameraUpdateFactory.newLatLng(LatLng(point.lat, point.lng)), animate, MapMotion.CAMERA_FIT_MS)
    }

    private fun move(update: org.maplibre.android.camera.CameraUpdate, animate: Boolean, durationMs: Int) {
        val m = map ?: return
        if (animate && !reduceMotion) m.animateCamera(update, durationMs) else m.moveCamera(update)
    }

    var mapView: org.maplibre.android.maps.MapView? = null

    // endregion

    // region route layers (§3.2)

    private fun installRouteLayers(style: Style) {
        val opts = GeoJsonOptions().withLineMetrics(true)
        listOf(SRC_PAST, SRC_UP, SRC_PENDING).forEach { id ->
            if (style.getSource(id) == null) style.addSource(GeoJsonSource(id, FeatureCollection.fromFeatures(emptyList<Feature>()), opts))
        }
        val below = MapStyle.ROUTE_BELOW_LAYER
        val casing = color(palette.casing)
        val lime = color(palette.line)
        val past = color(palette.pastLine)
        val pending = color(palette.pending)
        val casingW = palette.casingWidth
        val lineW = palette.lineWidth

        fun add(layer: LineLayer) {
            if (style.getLayer(layer.id) == null) style.addLayerBelow(layer, below)
        }
        fun base(id: String, src: String, c: Int, w: Float, opacity: Float, dash: List<Float>? = null): LineLayer =
            LineLayer(id, src).withProperties(
                PropertyFactory.lineColor(c),
                PropertyFactory.lineWidth(w),
                PropertyFactory.lineOpacity(opacity),
                PropertyFactory.lineCap(Property.LINE_CAP_ROUND),
                PropertyFactory.lineJoin(Property.LINE_JOIN_ROUND),
                PropertyFactory.visibility(Property.NONE),
            ).also { layer ->
                if (dash != null) layer.setProperties(PropertyFactory.lineDasharray(dash.map { it / w }.toTypedArray()))
            }

        // Order = draw order: pending, then past legs, then upcoming legs (casing under line).
        add(base(L_PENDING, SRC_PENDING, pending, palette.pendingWidth, 1f, palette.pendingDash))
        add(base(L_PAST_CASING, SRC_PAST, casing, casingW, palette.pastOpacity))
        add(base(L_PAST_LINE, SRC_PAST, past, lineW, palette.pastOpacity))
        add(base(L_UP_CASING, SRC_UP, casing, casingW, 1f))
        add(base(L_UP_LINE, SRC_UP, lime, lineW, 1f))
        add(base(L_FB_PAST_CASING, SRC_PAST, casing, casingW, palette.pastOpacity, palette.fallbackDash))
        add(base(L_FB_PAST_LINE, SRC_PAST, past, lineW, palette.pastOpacity, palette.fallbackDash))
        add(base(L_FB_UP_CASING, SRC_UP, casing, casingW, 1f, palette.fallbackDash))
        add(base(L_FB_UP_LINE, SRC_UP, lime, lineW, 1f, palette.fallbackDash))
    }

    /** Draws [newLines]; [animate] runs the 600 ms draw-from-Start animation when the geometry changed. */
    fun setRoute(newLines: RouteLines, dimRoute: Boolean, animate: Boolean) {
        val geometryChanged = (newLines.past + newLines.upcoming) != (lines.past + lines.upcoming)
        val styleChanged = newLines.dashed != lines.dashed
        lines = newLines
        val dimChanged = dim != dimRoute
        dim = dimRoute
        applyLines(animate = animate && geometryChanged && !styleChanged && !reduceMotion && !newLines.dashed)
        if (dimChanged) applyOpacity()
    }

    private fun applyLines(animate: Boolean) {
        val style = map?.style ?: return
        if (!styleReady && style.getLayer(L_UP_LINE) == null) return
        fun set(src: String, pts: List<GeoPoint>) {
            val source = style.getSourceAs<GeoJsonSource>(src) ?: return
            if (pts.size < 2) {
                source.setGeoJson(FeatureCollection.fromFeatures(emptyList<Feature>()))
            } else {
                source.setGeoJson(Feature.fromGeometry(LineString.fromLngLats(pts.map { Point.fromLngLat(it.lng, it.lat) })))
            }
        }
        set(SRC_PAST, lines.past)
        set(SRC_UP, lines.upcoming)
        set(SRC_PENDING, lines.pending)

        val dashed = lines.dashed
        fun vis(id: String, visible: Boolean) {
            style.getLayer(id)?.setProperties(PropertyFactory.visibility(if (visible) Property.VISIBLE else Property.NONE))
        }
        vis(L_PENDING, lines.pending.size >= 2)
        val hasPast = lines.past.size >= 2
        val hasUp = lines.upcoming.size >= 2
        vis(L_PAST_CASING, hasPast && !dashed); vis(L_PAST_LINE, hasPast && !dashed)
        vis(L_UP_CASING, hasUp && !dashed); vis(L_UP_LINE, hasUp && !dashed)
        vis(L_FB_PAST_CASING, hasPast && dashed); vis(L_FB_PAST_LINE, hasPast && dashed)
        vis(L_FB_UP_CASING, hasUp && dashed); vis(L_FB_UP_LINE, hasUp && dashed)
        applyOpacity()

        animator?.cancel()
        if (animate && (hasPast || hasUp)) {
            drawProgress = 0f
            applyProgress()
            animator = ValueAnimator.ofFloat(0f, 1f).apply {
                duration = MapMotion.ROUTE_DRAW_MS.toLong()
                interpolator = PathInterpolator(
                    MotionSpec.emphasized.x1, MotionSpec.emphasized.y1, MotionSpec.emphasized.x2, MotionSpec.emphasized.y2,
                )
                addUpdateListener {
                    drawProgress = it.animatedValue as Float
                    applyProgress()
                }
                start()
            }
        } else {
            drawProgress = 1f
            applyProgress()
        }
    }

    /** The draw animation runs past legs first, then upcoming ones (by distance share). */
    private fun applyProgress() {
        val style = map?.style ?: return
        val share = lines.pastShare
        val f = drawProgress
        val pastP = if (share <= 0f) 1f else (f / share).coerceIn(0f, 1f)
        val upP = if (share >= 1f) 1f else ((f - share) / (1f - share)).coerceIn(0f, 1f)
        fun grad(id: String, c: Int, p: Float) {
            style.getLayer(id)?.setProperties(PropertyFactory.lineGradient(gradient(c, p)))
        }
        grad(L_PAST_CASING, color(palette.casing), pastP)
        grad(L_PAST_LINE, color(palette.pastLine), pastP)
        grad(L_UP_CASING, color(palette.casing), upP)
        grad(L_UP_LINE, color(palette.line), upP)
    }

    /** While a pin is being moved the route dims to 35 % (components/MapScreen.dc.html). */
    private fun applyOpacity() {
        val style = map?.style ?: return
        val k = if (dim) 0.35f else 1f
        fun o(id: String, base: Float) {
            style.getLayer(id)?.setProperties(PropertyFactory.lineOpacity(base * k))
        }
        o(L_PENDING, 1f)
        listOf(L_PAST_CASING, L_PAST_LINE, L_FB_PAST_CASING, L_FB_PAST_LINE).forEach { o(it, palette.pastOpacity) }
        listOf(L_UP_CASING, L_UP_LINE, L_FB_UP_CASING, L_FB_UP_LINE).forEach { o(it, 1f) }
    }

    private fun gradient(c: Int, progress: Float): Expression =
        Expression.step(Expression.lineProgress(), Expression.color(c), Expression.stop(progress.coerceAtLeast(0f) + 0.0001f, Expression.color(Color.TRANSPARENT)))

    // endregion

    private fun color(hex: String): Int = Color.parseColor(hex)

    companion object {
        private const val SRC_PAST = "route-past"
        private const val SRC_UP = "route-upcoming"
        private const val SRC_PENDING = "route-pending"
        private const val L_PENDING = "route-pending-line"
        private const val L_PAST_CASING = "route-past-casing"
        private const val L_PAST_LINE = "route-past-line"
        private const val L_UP_CASING = "route-up-casing"
        private const val L_UP_LINE = "route-up-line"
        private const val L_FB_PAST_CASING = "route-fb-past-casing"
        private const val L_FB_PAST_LINE = "route-fb-past-line"
        private const val L_FB_UP_CASING = "route-fb-up-casing"
        private const val L_FB_UP_LINE = "route-fb-up-line"
    }
}
